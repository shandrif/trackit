#!/bin/sh
# Assemble index.html from base.html (head, base styles, page markup) and the src files.
cd "$(dirname "$0")"
python3 - <<'PY'
base = open("base.html", encoding="utf-8").read()
head, rest = base.split("</style>", 1)            # head + base CSS | page markup + old script
markup = rest.split("\n<script>\n", 1)[0]          # page markup only
css = "".join(open(f, encoding="utf-8").read() for f in ("src/extra.css", "src/motion.css"))
js = "\n".join(open(f, encoding="utf-8").read() for f in ("src/app.js", "src/excel.js", "src/motion.js"))
out = head + css + "</style>" + markup + "\n<script>\n" + js + "\n</script>\n</body>\n</html>\n"
open("index.html", "w", encoding="utf-8").write(out)
print("index.html built")
PY

# The scheduled alert email attaches the same Excel as the Alerts page button, plus a PDF.
# Write supabase/functions/trackit-email/report.js from src/excel.js + the PDF source, so they never drift apart.
python3 - <<'PY'
import re
app = open("src/app.js", encoding="utf-8").read()
def pick(pat):
    m = re.search(pat, app, re.M)
    if not m: raise SystemExit("build.sh: helper not found in app.js: " + pat)
    return m.group(0)
helpers = "\n".join(pick(p) for p in [r"^const DUE_DAYS = .*$", r"^const MONTHS = .*$", r"^const todayUTC = .*$", r"^const daysLeft = .*$",
    r"^const statusOf = .*$", r"^const STATUS_LABEL = .*$", r"^const placeOf = .*$", r"^const isDept = .*$", r"^const eid = .*$"])
xl = open("src/excel.js", encoding="utf-8").read()
old = "async function xlSave(wb, name){"
if xl.count(old) != 1: raise SystemExit("build.sh: xlSave not found in src/excel.js")
xl = xl.replace(old, old + " XL_OUT = { name, buf: new Uint8Array(await wb.xlsx.writeBuffer()) }; return;", 1)
pdf = open("supabase/functions/trackit-email/pdf-src.js", encoding="utf-8").read()
prelude = '''// GENERATED by build.sh from src/excel.js and supabase/functions/trackit-email/pdf-src.js. Do not edit by hand.
// Lets the scheduled email build exactly the same Excel as the "Download Excel" button on the Alerts page, plus a PDF.
let S = null, XL_OUT = null, XL_ERR = null;
const window = {};
const isAdmin = () => true;            // the email goes to trusted receivers: Iqama and mobile included
const scopeName = () => "";
const toast = m => { if (m !== "Excel downloaded") XL_ERR = m; };
function remindedMap(){ return S.rem; }
const mapOf = e => e.unit_kind === "store" ? (S.map[e.unit] || null) : null;
const geo = (k, e) => { const m = mapOf(e); if (m) return m[k]; return e.unit_kind === "dept" ? e.unit : e.unit_kind === "unassigned" ? "Unassigned" : ""; };
const GROUPS = { am: ["", e => geo("area_manager", e)], rom: ["", e => geo("rom", e)], city: ["", e => geo("city", e)], region: ["", e => geo("region", e)] };
'''
exports = '''
function setData(d){ S = { emps: d.emps, left: d.left || [], map: d.map, rem: d.rem || {}, me: { full_name: "Trackit (scheduled email)", role: "admin" }, filters: { am: "", rom: "", city: "", region: "" } }; }
export async function makeAlertsXlsx(ExcelJS, d){
  setData(d); window.ExcelJS = ExcelJS; XL_OUT = null; XL_ERR = null;
  await downloadAlertsExcel(null);
  if (!XL_OUT) throw new Error(XL_ERR || "Excel file was not made");
  return XL_OUT;
}
export function makeAlertsPdf(jsPDF, autoTable, d){
  setData(d);
  return { name: `Trackit Alerts - ${xlStamp()}.pdf`, buf: makeAlertsPdfDoc(jsPDF, autoTable) };
}
'''
open("supabase/functions/trackit-email/report.js", "w", encoding="utf-8").write(prelude + helpers + "\n" + xl + "\n" + pdf + exports)
print("supabase/functions/trackit-email/report.js built")
PY
